"""Optional Level 1 behavioral cloning warm start before online PPO.

Training samples are generated by a go-to-goal controller; this is supervised
pretraining, not evidence of PPO convergence or multi-obstacle competency.
"""

import argparse
import json
from pathlib import Path

import numpy as np
import torch
from torch.nn import functional as F

from ai_local_planner.configs.settings import load_config
from ai_local_planner.environments.agv_motion_env import AGVMotionEnv
from ai_local_planner.trainers.expert import goal_tracking_action
from ai_local_planner.trainers.ppo_agent import PPOAgent


def collect_expert(episodes: int, seed: int, max_steps: int):
    rng = np.random.default_rng(seed)
    env = AGVMotionEnv(level=1, randomize=True, max_steps=max_steps)
    observations, actions = [], []
    successes = 0
    try:
        for ep in range(episodes):
            obs, _ = env.reset(seed=seed + ep)
            # Broad heading disturbances teach recovery, not just straight drive.
            if ep % 2:
                env.pose[1] = rng.uniform(.85, 3.15)
                env.pose[2] = rng.uniform(-1.35, 1.35)
                obs = env._observe()
            for _ in range(max_steps):
                action = goal_tracking_action(obs)
                observations.append(obs)
                actions.append(action)
                obs, _, terminated, truncated, info = env.step(action)
                if terminated or truncated:
                    successes += int(info["success"])
                    break
    finally:
        env.close()
    return np.stack(observations), np.stack(actions), successes


def pretrain(args):
    torch.manual_seed(args.seed)
    torch.set_num_threads(1)
    obs, labels, teacher_successes = collect_expert(args.episodes, args.seed,
                                                     args.max_episode_steps)
    agent = PPOAgent(load_config()["ppo"], device=args.device)
    network = agent.network
    optimizer = torch.optim.Adam(network.parameters(), lr=args.learning_rate)
    device = agent.device
    dataset_obs = torch.as_tensor(obs, device=device)
    dataset_action = torch.as_tensor(labels, device=device)
    for epoch in range(args.epochs):
        # Keep ~10% held out to monitor imitation fit independently of train samples.
        permutation = torch.randperm(len(obs), device=device)
        train_n = int(.9 * len(obs))
        train_indices, valid_indices = permutation[:train_n], permutation[train_n:]
        network.train()
        total_loss = 0.
        batches = 0
        for batch in train_indices.split(args.batch_size):
            predictions = torch.tanh(network(dataset_obs[batch])[0])
            loss = F.mse_loss(predictions, dataset_action[batch])
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(network.parameters(), 1.)
            optimizer.step()
            total_loss += float(loss.detach())
            batches += 1
        network.eval()
        with torch.no_grad():
            val_error = float(F.mse_loss(torch.tanh(network(dataset_obs[valid_indices])[0]),
                                          dataset_action[valid_indices]))
        print(json.dumps({"epoch": epoch + 1, "train_mse": total_loss / batches,
                          "validation_mse": val_error}), flush=True)
    # Regenerate Adam's optimizer; teacher update history should not affect PPO updates.
    agent.optimizer = torch.optim.Adam(network.parameters(),
                                      lr=agent.config["learning_rate"], eps=1e-5)
    agent.save(args.output, 0, 1, method="behavioral_cloning_pretrain",
               teacher_episodes=args.episodes, teacher_success_rate=teacher_successes / args.episodes,
               teacher_states=len(obs), validation_mse=val_error)
    print(json.dumps({"saved": str(args.output), "teacher_success_rate":
                      teacher_successes / args.episodes, "samples": len(obs),
                      "validation_mse": val_error}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--episodes", type=int, default=100)
    parser.add_argument("--max-episode-steps", type=int, default=600)
    parser.add_argument("--epochs", type=int, default=15)
    parser.add_argument("--batch-size", type=int, default=256)
    parser.add_argument("--learning-rate", type=float, default=0.001)
    parser.add_argument("--seed", type=int, default=31415)
    parser.add_argument("--device", choices=["cpu", "cuda"], default="cpu")
    parser.add_argument("--output", type=Path,
                        default=Path("ai_local_planner/checkpoints/expert_pretrained.pth"))
    args = parser.parse_args()
    if min(args.episodes, args.epochs, args.batch_size, args.max_episode_steps) < 1:
        parser.error("episodes, epochs, batch size and horizon must be positive")
    pretrain(args)
